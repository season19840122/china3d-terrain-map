    const modal = document.getElementById('mountainModal');
    const title = document.getElementById('mountainModalTitle');
    const meta = document.getElementById('mountainModalMeta');
    const intro = document.getElementById('mountainModalIntro');
    const culture = document.getElementById('mountainModalCulture');

    function getMountainName(text) {
        return text.replace(/^⛰\s*/, '').replace(/\s+\d+m\s*$/, '').trim();
    }

    function closeModal() {
        modal.classList.remove('show');
        modal.setAttribute('aria-hidden', 'true');
    }

    function openModal(name, altitude) {
        const info = mountains[name];
        const fallback = ['中国名山', '这座山是地图中标注的重要山岳地标，兼具独特的自然地貌与区域生态价值。', '山川常被赋予人文想象；当地的历史记忆、游览传统与民间传说，为它留下丰富的文化意味。'];
        const [region, mountainIntro, mountainCulture] = info || fallback;
        title.textContent = name;
        meta.textContent = region + ' · 海拔 ' + altitude + ' 米';
        intro.textContent = mountainIntro;
        culture.textContent = mountainCulture;
        modal.classList.add('show');
        modal.setAttribute('aria-hidden', 'false');
    }

    document.addEventListener('click', function (event) {
        const label = event.target.closest('.label-mountain');
        if (label) {
            event.preventDefault();
            event.stopPropagation();
            const match = label.textContent.match(/\s(\d+)m\s*$/);
            openModal(getMountainName(label.textContent), match ? match[1] : '--');
            return;
        }
        if (event.target.closest('[data-mountain-close]')) closeModal();
    });

    document.addEventListener('keydown', function (event) {
        if (event.key === 'Escape') closeModal();
    });
